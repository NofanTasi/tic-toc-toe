export type TranslationKey = keyof typeof TRANSLATIONS.EN;

export function t(
  lang: Language | string = 'EN',
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const selectedLang = (lang && lang in TRANSLATIONS ? lang : 'EN') as Language;
  const dict = TRANSLATIONS[selectedLang] || TRANSLATIONS.EN;
  let text: string = (dict as Record<string, string>)[key] || (TRANSLATIONS.EN as Record<string, string>)[key] || String(key);
  if (params) {
    Object.entries(params).forEach(([paramKey, value]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(value));
    });
  }
  return text;
}
